#!/usr/bin/env python3
"""BulumOS Phase 8: generate src/bgfx_font.h from a PSF1 console font.

Extracts 8x16 glyphs for ASCII 32..126 from a Linux console font
(e.g. /usr/share/consolefonts/Lat15-Fixed16.psf.gz) and emits a C
header with the glyph data.  Deterministic: the generated header is
committed to the repository; regenerate only when changing the source
font.

Usage: python3 tools/gen-bgfx-font.py [path-to.psf] [output.h]
"""

import gzip
import struct
import sys

PSF1_MAGIC = 0x0436


def load_psf(path):
    data = open(path, "rb").read()
    if data.startswith(b"\x1f\x8b"):
        data = gzip.decompress(data)
    magic, mode, charsize = struct.unpack("<HBB", data[:4])
    if magic != PSF1_MAGIC:
        sys.exit("error: not a PSF1 font: %s" % path)
    nchars = 512 if mode & 0x01 else 256
    if charsize != 16:
        sys.exit("error: need an 8x16 (charsize 16) font, got %d" % charsize)
    glyphs = []
    for i in range(nchars):
        off = 4 + i * charsize
        glyphs.append(data[off:off + charsize])
    return glyphs


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/consolefonts/Lat15-Fixed16.psf.gz"
    out = sys.argv[2] if len(sys.argv) > 2 else "src/bgfx_font.h"
    glyphs = load_psf(src)
    first, last = 32, 126

    lines = []
    lines.append("/* Generated by tools/gen-bgfx-font.py - do not edit by hand. */")
    lines.append("/* 8x16 bitmap font, ASCII %d..%d (%d glyphs). */" % (first, last, last - first + 1))
    lines.append("#ifndef BGFX_FONT_DATA_H")
    lines.append("#define BGFX_FONT_DATA_H")
    lines.append("#include <stdint.h>")
    lines.append("#define BGFX_FONT_W 8")
    lines.append("#define BGFX_FONT_H 16")
    lines.append("#define BGFX_FONT_FIRST %d" % first)
    lines.append("#define BGFX_FONT_LAST %d" % last)
    lines.append("static const uint8_t bgfx_font_data[%d][%d] = {" % (last - first + 1, 16))
    for c in range(first, last + 1):
        g = glyphs[c]
        rows = ",".join("0x%02x" % b for b in g)
        lines.append("    { %s }," % rows)
    lines.append("};")
    lines.append("#endif /* BGFX_FONT_DATA_H */")

    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%d glyphs, %d bytes)" % (out, last - first + 1, len(glyphs) * 16))


if __name__ == "__main__":
    main()