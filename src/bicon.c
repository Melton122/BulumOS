static uint16_t cache[sizeof(ICONS) / sizeof(ICONS[0])][BICON_GRID];
static int cache_built = 0;

static uint16_t row_to_u16(const char *row)
{
    uint16_t v = 0;
    for (int i = 0; i < BICON_GRID; i++)
        if (row[i] == '#')
            v |= (uint16_t)(0x8000u >> i);
    return v;
}

static void build_cache(void)
{
    if (cache_built)
        return;
    for (size_t i = 0; i < sizeof(ICONS) / sizeof(ICONS[0]); i++)
        for (int r = 0; r < BICON_GRID; r++)
            cache[i][r] = row_to_u16(ICONS[i].rows[r]);
    cache_built = 1;
}

static const icon_def_t *find(const char *name)
{
    if (!name)
        return NULL;
    for (size_t i = 0; i < sizeof(ICONS) / sizeof(ICONS[0]); i++)
        if (strcmp(ICONS[i].name, name) == 0)
            return &ICONS[i];
    return NULL;
}

int bicon_exists(const char *name)
{
    return find(name) != NULL;
}

const uint16_t *bicon_glyph(const char *name)
{
    const icon_def_t *d = find(name);
    if (!d)
        return NULL;
    build_cache();
    return cache[d - ICONS];
}

int bicon_role(const char *name)
{
    const icon_def_t *d = find(name);
    return d ? d->role : 0;
}

void bicon_scaled(const uint16_t *glyph, int size,
                  uint32_t on, uint32_t off, uint32_t *out)
{
    if (!glyph || !out || size <= 0)
        return;
    for (int y = 0; y < size; y++) {
        int sy = y * BICON_GRID / size;
        for (int x = 0; x < size; x++) {
            int sx = x * BICON_GRID / size;
            uint16_t row = glyph[sy];
            int bit = (row & (0x8000u >> sx)) ? 1 : 0;
            out[y * size + x] = bit ? on : off;
        }
    }
}